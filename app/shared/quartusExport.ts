// Generates the files for "Export to Quartus" (spec section 7.8). Pure
// functions: the main process writes the result to disk. Syntax is limited to
// what Quartus Prime Lite 17.1 accepts.
import { findBoardBit, type BoardDefinition } from './board';
import type { Message } from './messages';
import { portBitName, sortAssignments, validatePins } from './pins';
import type { ExportLevel, NanoLogicProject, PinAssignment } from './project';
import type { TopPort } from './toolTypes';

export const QUARTUS_VERSION = '17.1';
export const QUARTUS_VERSION_FULL = '17.1.0';

export interface ExportSource {
  /** Project-relative path, forward slashes. */
  path: string;
  text: string;
}

export interface ExportInput {
  project: NanoLogicProject;
  board: BoardDefinition;
  ports: TopPort[];
  sources: ExportSource[];
  level: ExportLevel;
  /** Fixed time for reproducible output (tests, examples). */
  date: Date;
}

export interface ExportFile {
  /** Path inside the export folder, forward slashes. */
  path: string;
  content: string;
}

export interface ExportOutput {
  folderName: string;
  files: ExportFile[];
  messages: Message[];
}

interface ResolvedPin {
  name: string; // port or port[bit]
  port: TopPort;
  bit: number | null;
  boardId: string;
  pin: string;
  ioStandard: string;
  kind: string;
  activeLow: boolean;
  frequencyHz?: number;
}

const MONTHS = ['JANUARY', 'FEBRUARY', 'MARCH', 'APRIL', 'MAY', 'JUNE', 'JULY', 'AUGUST', 'SEPTEMBER', 'OCTOBER', 'NOVEMBER', 'DECEMBER'];

function pad2(n: number): string {
  return String(n).padStart(2, '0');
}

/** Quartus-style timestamp, e.g. "14:32:02  MARCH 26, 2026" (local time, two spaces). */
export function quartusDate(d: Date): string {
  return `${pad2(d.getHours())}:${pad2(d.getMinutes())}:${pad2(d.getSeconds())}  ${MONTHS[d.getMonth()]} ${d.getDate()}, ${d.getFullYear()}`;
}

/** Tcl-safe quoting for assignment values. */
function q(s: string): string {
  return /^[A-Za-z0-9_.\-/[\]]+$/.test(s) && !/[[\]]/.test(s) ? s : `"${s.replace(/(["\\$[\]])/g, '\\$1')}"`;
}

/** Target names in assignments: brackets are fine unescaped in -to arguments. */
function target(name: string): string {
  return /^[A-Za-z_][A-Za-z0-9_]*(\[\d+\])?$/.test(name) ? name : `"${name.replace(/"/g, '\\"')}"`;
}

function basename(p: string): string {
  return p.split('/').pop()!;
}

/** Destination names for sources under src/, de-duplicated. */
export function exportSourceNames(sources: ExportSource[]): Map<string, string> {
  const used = new Set<string>();
  const out = new Map<string, string>();
  for (const s of sources) {
    let name = basename(s.path);
    if (used.has(name.toLowerCase())) {
      const dot = name.lastIndexOf('.');
      let i = 2;
      while (used.has(`${name.slice(0, dot)}_${i}${name.slice(dot)}`.toLowerCase())) i++;
      name = `${name.slice(0, dot)}_${i}${name.slice(dot)}`;
    }
    used.add(name.toLowerCase());
    out.set(s.path, `src/${name}`);
  }
  return out;
}

export function resolvePins(ports: TopPort[], list: PinAssignment[], board: BoardDefinition): ResolvedPin[] {
  const out: ResolvedPin[] = [];
  for (const a of sortAssignments(list, ports)) {
    const port = ports.find((p) => p.name === a.port);
    const bb = findBoardBit(board, a.board);
    if (!port || !bb) continue;
    out.push({
      name: portBitName(port, a.bit),
      port,
      bit: a.bit,
      boardId: bb.id,
      pin: bb.pin,
      ioStandard: bb.group.ioStandard,
      kind: bb.group.kind,
      activeLow: bb.group.activeLow,
      frequencyHz: bb.group.frequencyHz,
    });
  }
  return out;
}

export function generateQpf(projectName: string, date: Date): string {
  return [
    '# Generated by NanoLogic for Quartus Prime Lite 17.1.',
    '',
    `QUARTUS_VERSION = "${QUARTUS_VERSION}"`,
    `DATE = "${quartusDate(date)}"`,
    '',
    '# Revisions',
    '',
    `PROJECT_REVISION = "${projectName}"`,
    '',
  ].join('\n');
}

export function generateQsf(input: ExportInput, sourceNames: string[], pins: ResolvedPin[], hasSdc: boolean): string {
  const { project, board } = input;
  const lines = [
    `# Generated by NanoLogic for the ${board.name}.`,
    `# Open ${project.name}.qpf in Quartus Prime Lite 17.1, then run Processing > Start Compilation.`,
    '# Pin locations and I/O standards come from the DE10-Lite User Manual.',
    '',
    `set_global_assignment -name FAMILY ${q(board.family)}`,
    `set_global_assignment -name DEVICE ${q(board.device)}`,
    `set_global_assignment -name TOP_LEVEL_ENTITY ${q(project.topLevelEntity)}`,
    `set_global_assignment -name ORIGINAL_QUARTUS_VERSION ${QUARTUS_VERSION_FULL}`,
    `set_global_assignment -name PROJECT_CREATION_TIME_DATE "${quartusDate(input.date)}"`,
    `set_global_assignment -name LAST_QUARTUS_VERSION "${QUARTUS_VERSION_FULL} Lite Edition"`,
    'set_global_assignment -name PROJECT_OUTPUT_DIRECTORY output_files',
    'set_global_assignment -name MIN_CORE_JUNCTION_TEMP 0',
    'set_global_assignment -name MAX_CORE_JUNCTION_TEMP 85',
    '',
    '# Source files',
    ...sourceNames.map((s) => `set_global_assignment -name VERILOG_FILE ${q(s)}`),
  ];
  if (hasSdc) lines.push(`set_global_assignment -name SDC_FILE ${q(`${project.name}.sdc`)}`);
  if (pins.length) {
    lines.push('', '# Pin assignments');
    for (const p of pins) lines.push(`set_location_assignment ${p.pin} -to ${target(p.name)}`);
    lines.push('', '# I/O standards');
    for (const p of pins) lines.push(`set_instance_assignment -name IO_STANDARD ${q(p.ioStandard)} -to ${target(p.name)}`);
  }
  lines.push('');
  return lines.join('\n');
}

export function generateSdc(pins: ResolvedPin[]): { text: string; clocks: number } {
  const clocks = pins.filter((p) => p.kind === 'clock' && p.frequencyHz);
  const lines = ['# Timing constraints generated by NanoLogic.', ''];
  for (const c of clocks) {
    const period = (1e9 / c.frequencyHz!).toFixed(3);
    lines.push(`# ${c.boardId}: ${c.frequencyHz! / 1e6} MHz`);
    lines.push(`create_clock -name {${c.name}} -period ${period} [get_ports {${c.name}}]`);
  }
  if (clocks.length === 0) lines.push('# No board clock is used by this design.');
  lines.push('', 'derive_clock_uncertainty', '');
  return { text: lines.join('\n'), clocks: clocks.length };
}

function levelHint(p: ResolvedPin): string {
  switch (p.kind) {
    case 'button':
      return '0 while pressed (active-low)';
    case 'switch':
      return '1 when up';
    case 'led':
      return 'lit when 1';
    case 'sevenseg':
      return 'segment lit when 0 (active-low)';
    case 'clock':
      return p.frequencyHz ? `${p.frequencyHz / 1e6} MHz clock` : 'clock';
    default:
      return '';
  }
}

export function generatePinTable(input: ExportInput, pins: ResolvedPin[]): { md: string; csv: string } {
  const header = ['Port', 'Direction', 'Board signal', 'Pin', 'I/O standard', 'Level'];
  const rows = pins.map((p) => [p.name, p.port.direction, p.boardId, p.pin, p.ioStandard, levelHint(p)]);
  const md = [
    `# Pin assignments for ${input.project.name}`,
    '',
    `Board: ${input.board.name} (${input.board.family} ${input.board.device}). Top-level entity: \`${input.project.topLevelEntity}\`.`,
    '',
    'Enter these in Quartus with Assignments > Pin Planner, or use the full project export (level 3).',
    '',
    `| ${header.join(' | ')} |`,
    `| ${header.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.join(' | ')} |`),
    '',
  ].join('\n');
  const csvCell = (s: string) => (/[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s);
  const csv = [header, ...rows].map((r) => r.map(csvCell).join(',')).join('\n') + '\n';
  return { md, csv };
}

export function generateExport(input: ExportInput): ExportOutput {
  const { project, board, level } = input;
  const messages: Message[] = validatePins(input.ports, project.pinAssignments, board).map((m) => ({
    ...m,
    source: 'export',
  }));
  const names = exportSourceNames(input.sources);
  const files: ExportFile[] = input.sources.map((s) => ({ path: names.get(s.path)!, content: s.text }));
  const pins = resolvePins(input.ports, project.pinAssignments, board);
  if (level >= 2) {
    const t = generatePinTable(input, pins);
    files.push({ path: 'pins.md', content: t.md }, { path: 'pins.csv', content: t.csv });
  }
  if (level >= 3) {
    const sdc = generateSdc(pins);
    files.push({ path: `${project.name}.qpf`, content: generateQpf(project.name, input.date) });
    files.push({
      path: `${project.name}.qsf`,
      content: generateQsf(
        input,
        input.sources.map((s) => names.get(s.path)!),
        pins,
        true,
      ),
    });
    files.push({ path: `${project.name}.sdc`, content: sdc.text });
    if (sdc.clocks === 0) {
      messages.push({ severity: 'warning', text: 'No port is mapped to a board clock, so the .sdc file has no clock constraint.', source: 'export' });
    }
  }
  return { folderName: `${project.name}_quartus`, files, messages };
}
