// "Export to Vivado" for Xilinx boards (Basys 3). Pure functions, like the
// Quartus export: the main process writes the result to disk. Level 3 writes
// an .xdc and a create_project.tcl script instead of a .xpr, so the project is
// created by whichever Vivado version the student has.
import type { BoardDefinition } from './board';
import type { Message } from './messages';
import { validatePins } from './pins';
import {
  exportSourceNames,
  generatePinTable,
  resolvePins,
  type ExportFile,
  type ExportInput,
  type ExportOutput,
  type ResolvedPin,
} from './quartusExport';

function headerLines(board: BoardDefinition, comment: string): string[] {
  const lines = [`${comment} Generated by NanoLogic for the ${board.name}.`];
  if (board.statusNote) lines.push(`${comment} ${board.statusNote.toUpperCase()}.`);
  return lines;
}

/** get_ports argument: bare for scalars, braced for bus bits. */
function portRef(name: string): string {
  return /\[/.test(name) ? `{${name}}` : name;
}

export function generateXdc(board: BoardDefinition, pins: ResolvedPin[]): string {
  const lines = [
    ...headerLines(board, '##'),
    `## Pin locations and I/O standards from Digilent's ${board.sourceFile ?? 'master XDC'}`,
    `## (github.com/Digilent/digilent-xdc, commit ${(board.sourceCommit ?? '').slice(0, 7)}). Only ports mapped in NanoLogic are listed.`,
    '',
  ];
  if (pins.length) {
    lines.push('## Pins');
    for (const p of pins) lines.push(`set_property -dict { PACKAGE_PIN ${p.pin} IOSTANDARD ${p.ioStandard} } [get_ports ${portRef(p.name)}]`);
    lines.push('');
  }
  const clocks = pins.filter((p) => p.kind === 'clock' && p.frequencyHz);
  if (clocks.length) {
    lines.push('## Clocks');
    clocks.forEach((c, i) => {
      const period = 1e9 / c.frequencyHz!;
      const name = i === 0 ? 'sys_clk_pin' : `sys_clk_pin_${c.name.replace(/\W/g, '_')}`;
      lines.push(
        `create_clock -add -name ${name} -period ${period.toFixed(3)} -waveform {0 ${(period / 2).toFixed(3)}} [get_ports ${portRef(c.name)}]`,
      );
    });
    lines.push('');
  }
  if (board.designProperties?.length) {
    lines.push('## Configuration options (from the master XDC)', ...board.designProperties, '');
  }
  return lines.join('\n');
}

/** Tcl-quoted file name component (braces protect spaces and special characters). */
function tclWord(s: string): string {
  return /^[A-Za-z0-9_.\-]+$/.test(s) ? s : `{${s}}`;
}

export function generateCreateProjectTcl(input: ExportInput, sourcePaths: string[], xdcName: string): string {
  const { project, board } = input;
  const fileJoin = (p: string) => `[file join $here ${p.split('/').map(tclWord).join(' ')}]`;
  return [
    ...headerLines(board, '#'),
    '#',
    `# Creates a Vivado project for the ${board.device} in a folder called "vivado" next to this script.`,
    '# In Vivado: Tools > Run Tcl Script..., then choose this file.',
    '# Or from a terminal in this folder: vivado -mode batch -source create_project.tcl',
    '# To start again, delete the "vivado" folder and run the script again.',
    '',
    'set here [file normalize [file dirname [info script]]]',
    `create_project ${tclWord(project.name)} [file join $here vivado] -part ${board.device}`,
    'set_property target_language Verilog [current_project]',
    '',
    '# Design sources (testbenches are not included)',
    'add_files -norecurse [list \\',
    ...sourcePaths.map((p) => `  ${fileJoin(p)} \\`),
    ']',
    '',
    '# Pin constraints',
    `add_files -fileset constrs_1 -norecurse ${fileJoin(xdcName)}`,
    '',
    `set_property top ${tclWord(project.topLevelEntity)} [current_fileset]`,
    'update_compile_order -fileset sources_1',
    'puts "NanoLogic: project created. Use Generate Bitstream in the Flow Navigator to build it."',
    '',
  ].join('\n');
}

export function generateVivadoExport(input: ExportInput): ExportOutput {
  const { project, board, level } = input;
  const messages: Message[] = validatePins(input.ports, project.pinAssignments, board).map((m) => ({ ...m, source: 'export' }));
  if (board.statusNote) {
    messages.push({ severity: 'warning', text: `${board.name} support is experimental: not yet verified on hardware.`, source: 'export' });
  }
  const names = exportSourceNames(input.sources);
  const files: ExportFile[] = input.sources.map((s) => ({ path: names.get(s.path)!, content: s.text }));
  const pins = resolvePins(input.ports, project.pinAssignments, board);
  if (level >= 2) {
    const t = generatePinTable(
      input,
      pins,
      'Add these to an .xdc constraints file in Vivado, or use the full project export (level 3), which writes the .xdc for you.',
    );
    files.push({ path: 'pins.md', content: t.md }, { path: 'pins.csv', content: t.csv });
  }
  if (level >= 3) {
    const xdcName = `${project.name}.xdc`;
    files.push({ path: xdcName, content: generateXdc(board, pins) });
    files.push({
      path: 'create_project.tcl',
      content: generateCreateProjectTcl(
        input,
        input.sources.map((s) => names.get(s.path)!),
        xdcName,
      ),
    });
    if (!pins.some((p) => p.kind === 'clock')) {
      messages.push({ severity: 'warning', text: 'No port is mapped to the board clock, so the .xdc has no create_clock.', source: 'export' });
    }
  }
  return { folderName: `${project.name}_vivado`, files, messages };
}
