import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { DE10_LITE } from '../../app/shared/board';
import { autoMap, mapPortToGroup, setAssignment, validatePins } from '../../app/shared/pins';
import { createProject, type NanoLogicProject, type PinAssignment } from '../../app/shared/project';
import { generateExport, generatePinTable, generateQpf, generateQsf, generateSdc, quartusDate, resolvePins } from '../../app/shared/quartusExport';
import type { TopPort } from '../../app/shared/toolTypes';
import { writeExport } from '../../app/main/exportFs';

const DATE = new Date(2026, 9, 30, 9, 15, 0); // local time, so output is the same in every time zone

const ports: TopPort[] = [
  { name: 'clk', direction: 'input', width: 1, msb: 0, lsb: 0, scalar: true },
  { name: 'KEY', direction: 'input', width: 2, msb: 1, lsb: 0, scalar: false },
  { name: 'leds', direction: 'output', width: 2, msb: 1, lsb: 0, scalar: false },
];

const pins: PinAssignment[] = [
  { port: 'clk', bit: null, board: 'MAX10_CLK1_50' },
  { port: 'KEY', bit: 0, board: 'KEY[0]' },
  { port: 'KEY', bit: 1, board: 'KEY[1]' },
  { port: 'leds', bit: 1, board: 'LEDR[9]' },
  { port: 'leds', bit: 0, board: 'LEDR[0]' },
];

function project(over: Partial<NanoLogicProject> = {}): NanoLogicProject {
  return { ...createProject({ name: 'demo', topLevelEntity: 'demo_top', designFiles: ['demo_top.v'] }), pinAssignments: pins, ...over };
}

describe('Quartus export files', () => {
  it('formats dates like Quartus', () => {
    expect(quartusDate(DATE)).toBe('09:15:00  OCTOBER 30, 2026');
  });

  it('generates the .qpf', () => {
    expect(generateQpf('demo', DATE)).toBe(
      ['# Generated by NanoLogic for Quartus Prime Lite 17.1.', '', 'QUARTUS_VERSION = "17.1"', 'DATE = "09:15:00  OCTOBER 30, 2026"', '', '# Revisions', '', 'PROJECT_REVISION = "demo"', ''].join('\n'),
    );
  });

  it('generates the .qsf with device, files, pins and I/O standards from the board file', () => {
    const input = { project: project(), board: DE10_LITE, ports, sources: [], level: 3 as const, date: DATE };
    const text = generateQsf(input, ['src/demo_top.v'], resolvePins(ports, pins, DE10_LITE), true);
    expect(text).toBe(
      [
        '# Generated by NanoLogic for the Terasic DE10-Lite.',
        '# Open demo.qpf in Quartus Prime Lite 17.1, then run Processing > Start Compilation.',
        '# Pin locations and I/O standards come from the DE10-Lite User Manual.',
        '',
        'set_global_assignment -name FAMILY "MAX 10"',
        'set_global_assignment -name DEVICE 10M50DAF484C7G',
        'set_global_assignment -name TOP_LEVEL_ENTITY demo_top',
        'set_global_assignment -name ORIGINAL_QUARTUS_VERSION 17.1.0',
        'set_global_assignment -name PROJECT_CREATION_TIME_DATE "09:15:00  OCTOBER 30, 2026"',
        'set_global_assignment -name LAST_QUARTUS_VERSION "17.1.0 Lite Edition"',
        'set_global_assignment -name PROJECT_OUTPUT_DIRECTORY output_files',
        'set_global_assignment -name MIN_CORE_JUNCTION_TEMP 0',
        'set_global_assignment -name MAX_CORE_JUNCTION_TEMP 85',
        '',
        '# Source files',
        'set_global_assignment -name VERILOG_FILE src/demo_top.v',
        'set_global_assignment -name SDC_FILE demo.sdc',
        '',
        '# Pin assignments',
        'set_location_assignment PIN_P11 -to clk',
        'set_location_assignment PIN_B8 -to KEY[0]',
        'set_location_assignment PIN_A7 -to KEY[1]',
        'set_location_assignment PIN_A8 -to leds[0]',
        'set_location_assignment PIN_B11 -to leds[1]',
        '',
        '# I/O standards',
        'set_instance_assignment -name IO_STANDARD "3.3-V LVTTL" -to clk',
        'set_instance_assignment -name IO_STANDARD "3.3 V SCHMITT TRIGGER" -to KEY[0]',
        'set_instance_assignment -name IO_STANDARD "3.3 V SCHMITT TRIGGER" -to KEY[1]',
        'set_instance_assignment -name IO_STANDARD "3.3-V LVTTL" -to leds[0]',
        'set_instance_assignment -name IO_STANDARD "3.3-V LVTTL" -to leds[1]',
        '',
      ].join('\n'),
    );
  });

  it('generates the .sdc with a 20 ns clock on the 50 MHz port', () => {
    expect(generateSdc(resolvePins(ports, pins, DE10_LITE)).text).toBe(
      [
        '# Timing constraints generated by NanoLogic.',
        '',
        '# MAX10_CLK1_50: 50 MHz',
        'create_clock -name {clk} -period 20.000 [get_ports {clk}]',
        '',
        'derive_clock_uncertainty',
        '',
      ].join('\n'),
    );
  });

  it('generates a readable pin table', () => {
    const input = { project: project(), board: DE10_LITE, ports, sources: [], level: 2 as const, date: DATE };
    const { md, csv } = generatePinTable(input, resolvePins(ports, pins, DE10_LITE));
    expect(csv.split('\n').slice(0, 3)).toEqual([
      'Port,Direction,Board signal,Pin,I/O standard,Level',
      'clk,input,MAX10_CLK1_50,PIN_P11,3.3-V LVTTL,50 MHz clock',
      'KEY[0],input,KEY[0],PIN_B8,3.3 V SCHMITT TRIGGER,0 while pressed (active-low)',
    ]);
    expect(md).toContain('| leds[1] | output | LEDR[9] | PIN_B11 | 3.3-V LVTTL | lit when 1 |');
  });

  it('exports the right files at each level and leaves testbenches out', () => {
    const p = project({ testbenchFiles: ['demo_tb.v'] });
    const sources = [{ path: 'demo_top.v', text: 'module demo_top; endmodule\n' }];
    const files = (level: 1 | 2 | 3) =>
      generateExport({ project: p, board: DE10_LITE, ports, sources, level, date: DATE })
        .files.map((f) => f.path)
        .sort();
    expect(files(1)).toEqual(['src/demo_top.v']);
    expect(files(2)).toEqual(['pins.csv', 'pins.md', 'src/demo_top.v']);
    expect(files(3)).toEqual(['demo.qpf', 'demo.qsf', 'demo.sdc', 'pins.csv', 'pins.md', 'src/demo_top.v']);
  });

  it('only assigns mapped ports and warns about the rest', () => {
    const out = generateExport({
      project: project({ pinAssignments: pins.filter((a) => a.port !== 'leds') }),
      board: DE10_LITE,
      ports,
      sources: [{ path: 'demo_top.v', text: '' }],
      level: 3,
      date: DATE,
    });
    const qsf = out.files.find((f) => f.path === 'demo.qsf')!.content;
    expect(qsf).not.toContain('leds');
    expect(out.messages.some((m) => m.severity === 'warning' && m.text.includes('"leds"'))).toBe(true);
  });

  it('writes files that resolve on this OS (forward slashes, de-duplicated names)', async () => {
    const sources = [
      { path: 'rtl/a.v', text: 'module a; endmodule\n' },
      { path: 'other/a.v', text: 'module a2; endmodule\n' },
    ];
    const out = generateExport({ project: project(), board: DE10_LITE, ports, sources, level: 3, date: DATE });
    const qsf = out.files.find((f) => f.path === 'demo.qsf')!.content;
    expect(qsf).not.toContain('\\');
    expect(qsf).not.toContain('\r');
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'nl-export-'));
    await writeExport(dir, out.files);
    // Read back the way Quartus does: each VERILOG_FILE / SDC_FILE relative to the .qsf.
    const refs = [...qsf.matchAll(/-name (?:VERILOG_FILE|SDC_FILE) (\S+)/g)].map((m) => m[1]);
    expect(refs).toEqual(['src/a.v', 'src/a_2.v', 'demo.sdc']);
    for (const r of refs) expect(fs.existsSync(path.resolve(dir, r)), r).toBe(true);
    expect(fs.readFileSync(path.join(dir, 'src', 'a_2.v'), 'utf8')).toContain('module a2');
  });
});

describe('pin mapping', () => {
  const starterPorts: TopPort[] = [
    { name: 'MAX10_CLK1_50', direction: 'input', width: 1, msb: 0, lsb: 0, scalar: true },
    { name: 'KEY', direction: 'input', width: 2, msb: 1, lsb: 0, scalar: false },
    { name: 'SW', direction: 'input', width: 10, msb: 9, lsb: 0, scalar: false },
    { name: 'LEDR', direction: 'output', width: 10, msb: 9, lsb: 0, scalar: false },
    { name: 'HEX0', direction: 'output', width: 8, msb: 7, lsb: 0, scalar: false },
    { name: 'other', direction: 'output', width: 1, msb: 0, lsb: 0, scalar: true },
  ];

  it('auto-maps standard port names bit for bit', () => {
    const m = autoMap(starterPorts, DE10_LITE);
    expect(m).toHaveLength(1 + 2 + 10 + 10 + 8);
    expect(m).toContainEqual({ port: 'MAX10_CLK1_50', bit: null, board: 'MAX10_CLK1_50' });
    expect(m).toContainEqual({ port: 'SW', bit: 9, board: 'SW[9]' });
    expect(m).toContainEqual({ port: 'HEX0', bit: 7, board: 'HEX0[7]' });
    expect(m.some((a) => a.port === 'other')).toBe(false);
    expect(validatePins(starterPorts, m, DE10_LITE).filter((x) => x.severity === 'error')).toEqual([]);
  });

  it('maps narrower ports onto part of a group, e.g. a 7-bit digit to HEX1[6:0]', () => {
    const seg: TopPort = { name: 'seg_tens', direction: 'output', width: 7, msb: 6, lsb: 0, scalar: false };
    const m = mapPortToGroup([], seg, DE10_LITE.groups.find((g) => g.name === 'HEX1')!);
    expect(m.map((a) => a.board)).toEqual(['HEX1[0]', 'HEX1[1]', 'HEX1[2]', 'HEX1[3]', 'HEX1[4]', 'HEX1[5]', 'HEX1[6]']);
  });

  it('reports direction mismatches, pins used twice and out-of-range bits', () => {
    const btn: TopPort = { name: 'ped_button', direction: 'input', width: 1, msb: 0, lsb: 0, scalar: true };
    const lamp: TopPort = { name: 'lamp', direction: 'output', width: 1, msb: 0, lsb: 0, scalar: true };
    const bus: TopPort = { name: 'd', direction: 'output', width: 2, msb: 1, lsb: 0, scalar: false };
    let list = setAssignment([], 'ped_button', null, 'LEDR[0]');
    list = setAssignment(list, 'lamp', null, 'LEDR[1]');
    list = setAssignment(list, 'd', 0, 'LEDR[1]');
    list = setAssignment(list, 'd', 5, 'LEDR[2]');
    const msgs = validatePins([btn, lamp, bus], list, DE10_LITE).map((m) => `${m.severity}: ${m.text}`);
    expect(msgs).toContainEqual(expect.stringMatching(/^error: Input "ped_button" is mapped to LEDR\[0\], which is an output/));
    expect(msgs).toContainEqual(expect.stringMatching(/^error: lamp and d\[0\] are all mapped to PIN_A9/));
    expect(msgs).toContainEqual(expect.stringMatching(/^error: "d\[5\]" is outside the port's range/));
    expect(msgs).toContainEqual(expect.stringMatching(/^warning: Only 1 of the 2 bits of "d"/));
  });

  it('gives active-low hints', () => {
    const rst: TopPort = { name: 'rst_n', direction: 'input', width: 1, msb: 0, lsb: 0, scalar: true };
    const go: TopPort = { name: 'go', direction: 'input', width: 1, msb: 0, lsb: 0, scalar: true };
    const list = [
      { port: 'rst_n', bit: null, board: 'SW[0]' },
      { port: 'go', bit: null, board: 'KEY[0]' },
    ];
    const msgs = validatePins([rst, go], list, DE10_LITE).map((m) => `${m.severity}: ${m.text}`);
    expect(msgs).toContainEqual(expect.stringMatching(/^warning: "rst_n" looks active-low.*SW is active-high/));
    expect(msgs).toContainEqual(expect.stringMatching(/^info: KEY buttons read 0 while pressed/));
  });
});
