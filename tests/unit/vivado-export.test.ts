import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { BASYS3, DE10_LITE } from '../../app/shared/board';
import { generateBoardExport } from '../../app/shared/boardExport';
import { autoMap } from '../../app/shared/pins';
import { createProject, parseProject, type NanoLogicProject, type PinAssignment } from '../../app/shared/project';
import { resolvePins } from '../../app/shared/quartusExport';
import type { TopPort } from '../../app/shared/toolTypes';
import { generateCreateProjectTcl, generateXdc } from '../../app/shared/vivadoExport';
import { writeExport } from '../../app/main/exportFs';
import { analyseProject } from '../../app/main/toolchain/analysis';

const DATE = new Date(2026, 10, 2, 9, 0, 0);
const ROOT = path.resolve(__dirname, '../..');

const ports: TopPort[] = [
  { name: 'clk', direction: 'input', width: 1, msb: 0, lsb: 0, scalar: true },
  { name: 'btnC', direction: 'input', width: 1, msb: 0, lsb: 0, scalar: true },
  { name: 'an', direction: 'output', width: 2, msb: 1, lsb: 0, scalar: false },
];
const pins: PinAssignment[] = [
  { port: 'clk', bit: null, board: 'clk' },
  { port: 'btnC', bit: null, board: 'btnC' },
  { port: 'an', bit: 0, board: 'an[0]' },
  { port: 'an', bit: 1, board: 'an[1]' },
];

function project(over: Partial<NanoLogicProject> = {}): NanoLogicProject {
  return {
    ...createProject({ name: 'demo', boardId: 'basys3', topLevelEntity: 'demo_top', designFiles: ['demo_top.v'] }),
    pinAssignments: pins,
    ...over,
  };
}

describe('Vivado export (Basys 3)', () => {
  it('generates an .xdc with only the mapped ports, the 100 MHz clock and the config options', () => {
    expect(generateXdc(BASYS3, resolvePins(ports, pins, BASYS3))).toBe(
      [
        '## Generated by NanoLogic for the Digilent Basys 3.',
        '## EXPERIMENTAL - NOT YET VERIFIED ON HARDWARE.',
        "## Pin locations and I/O standards from Digilent's Basys-3-Master.xdc",
        '## (github.com/Digilent/digilent-xdc, commit c8644a9). Only ports mapped in NanoLogic are listed.',
        '',
        '## Pins',
        'set_property -dict { PACKAGE_PIN W5 IOSTANDARD LVCMOS33 } [get_ports clk]',
        'set_property -dict { PACKAGE_PIN U18 IOSTANDARD LVCMOS33 } [get_ports btnC]',
        'set_property -dict { PACKAGE_PIN U2 IOSTANDARD LVCMOS33 } [get_ports {an[0]}]',
        'set_property -dict { PACKAGE_PIN U4 IOSTANDARD LVCMOS33 } [get_ports {an[1]}]',
        '',
        '## Clocks',
        'create_clock -add -name sys_clk_pin -period 10.000 -waveform {0 5.000} [get_ports clk]',
        '',
        '## Configuration options (from the master XDC)',
        'set_property CONFIG_VOLTAGE 3.3 [current_design]',
        'set_property CFGBVS VCCO [current_design]',
        'set_property BITSTREAM.GENERAL.COMPRESS TRUE [current_design]',
        'set_property BITSTREAM.CONFIG.CONFIGRATE 33 [current_design]',
        'set_property CONFIG_MODE SPIx4 [current_design]',
        '',
      ].join('\n'),
    );
  });

  it('generates a create_project.tcl for the xc7a35tcpg236-1', () => {
    const input = { project: project(), board: BASYS3, ports, sources: [], level: 3 as const, date: DATE };
    expect(generateCreateProjectTcl(input, ['src/demo_top.v', 'src/my file.v'], 'demo.xdc')).toBe(
      [
        '# Generated by NanoLogic for the Digilent Basys 3.',
        '# EXPERIMENTAL - NOT YET VERIFIED ON HARDWARE.',
        '#',
        '# Creates a Vivado project for the xc7a35tcpg236-1 in a folder called "vivado" next to this script.',
        '# In Vivado: Tools > Run Tcl Script..., then choose this file.',
        '# Or from a terminal in this folder: vivado -mode batch -source create_project.tcl',
        '# To start again, delete the "vivado" folder and run the script again.',
        '',
        'set here [file normalize [file dirname [info script]]]',
        'create_project demo [file join $here vivado] -part xc7a35tcpg236-1',
        'set_property target_language Verilog [current_project]',
        '',
        '# Design sources (testbenches are not included)',
        'add_files -norecurse [list \\',
        '  [file join $here src demo_top.v] \\',
        '  [file join $here src {my file.v}] \\',
        ']',
        '',
        '# Pin constraints',
        'add_files -fileset constrs_1 -norecurse [file join $here demo.xdc]',
        '',
        'set_property top demo_top [current_fileset]',
        'update_compile_order -fileset sources_1',
        'puts "NanoLogic: project created. Use Generate Bitstream in the Flow Navigator to build it."',
        '',
      ].join('\n'),
    );
  });

  it('exports the right files at each level, labelled experimental', () => {
    const sources = [{ path: 'demo_top.v', text: 'module demo_top; endmodule\n' }];
    const run = (level: 1 | 2 | 3) => generateBoardExport({ project: project({ testbenchFiles: ['tb.v'] }), board: BASYS3, ports, sources, level, date: DATE });
    expect(run(1).files.map((f) => f.path)).toEqual(['src/demo_top.v']);
    expect(run(2).files.map((f) => f.path).sort()).toEqual(['pins.csv', 'pins.md', 'src/demo_top.v']);
    const l3 = run(3);
    expect(l3.folderName).toBe('demo_vivado');
    expect(l3.files.map((f) => f.path).sort()).toEqual(['create_project.tcl', 'demo.xdc', 'pins.csv', 'pins.md', 'src/demo_top.v']);
    expect(l3.messages).toContainEqual(expect.objectContaining({ severity: 'warning', text: expect.stringMatching(/experimental/) }));
    const md = l3.files.find((f) => f.path === 'pins.md')!.content;
    expect(md).toContain('**Experimental - not yet verified on hardware.**');
    expect(md).toContain('| btnC | input | btnC | U18 | LVCMOS33 | 1 while pressed |');
    expect(md).toContain('| an[0] | output | an[0] | U2 | LVCMOS33 | digit enabled when 0 (active-low) |');
  });

  it('leaves create_clock out when the clock is not mapped', () => {
    const out = generateBoardExport({
      project: project({ pinAssignments: pins.filter((p) => p.port !== 'clk') }),
      board: BASYS3,
      ports,
      sources: [{ path: 'demo_top.v', text: '' }],
      level: 3,
      date: DATE,
    });
    expect(out.files.find((f) => f.path === 'demo.xdc')!.content).not.toContain('create_clock');
    expect(out.messages.some((m) => /no create_clock/.test(m.text))).toBe(true);
  });

  it('still produces Quartus files for the DE10-Lite', () => {
    const p = { ...createProject({ name: 'q', topLevelEntity: 't', designFiles: ['t.v'] }), pinAssignments: [] };
    const out = generateBoardExport({ project: p, board: DE10_LITE, ports: [], sources: [{ path: 't.v', text: '' }], level: 3, date: DATE });
    expect(out.folderName).toBe('q_quartus');
    expect(out.files.map((f) => f.path)).toContain('q.qsf');
  });
});

describe('Basys 3 starter export (examples/basys3-starter-export)', () => {
  const dir = path.join(ROOT, 'examples/basys3-starter');
  const EXPORT_DIR = path.join(ROOT, 'examples/basys3-starter-export');

  it('matches a fresh level 3 export', async () => {
    const proj = parseProject(fs.readFileSync(path.join(dir, 'basys3_starter.nlproj'), 'utf8'));
    const analysis = await analyseProject(dir, proj);
    expect(analysis.ok).toBe(true);
    const out = generateBoardExport({
      project: { ...proj, pinAssignments: autoMap(analysis.ports, BASYS3) },
      board: BASYS3,
      ports: analysis.ports,
      sources: proj.designFiles.map((f) => ({ path: f, text: fs.readFileSync(path.join(dir, f), 'utf8') })),
      level: 3,
      date: DATE,
    });
    expect(out.messages.filter((m) => m.severity === 'error')).toEqual([]);
    if (process.env.UPDATE_EXAMPLES === '1') {
      fs.rmSync(EXPORT_DIR, { recursive: true, force: true });
      await writeExport(EXPORT_DIR, out.files);
    }
    for (const f of out.files) {
      const disk = fs.readFileSync(path.join(EXPORT_DIR, ...f.path.split('/')), 'utf8');
      expect(disk, `${f.path} is out of date: run npm run examples:export`).toBe(f.content);
    }
    const xdc = out.files.find((f) => f.path === 'basys3_starter.xdc')!.content;
    expect((xdc.match(/PACKAGE_PIN/g) ?? []).length).toBe(1 + 16 + 5 + 16 + 7 + 1 + 4);
    expect(xdc).toContain('create_clock -add -name sys_clk_pin -period 10.000');
    const tcl = out.files.find((f) => f.path === 'create_project.tcl')!.content;
    expect(tcl).toContain('-part xc7a35tcpg236-1');
    expect(tcl).toContain('set_property top top [current_fileset]');
    expect(tcl).not.toContain('top_tb');
  });

  it('writes files that resolve from the script on this OS', async () => {
    const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'nl-vivado-'));
    const out = generateBoardExport({
      project: project(),
      board: BASYS3,
      ports,
      sources: [{ path: 'rtl/demo_top.v', text: 'module demo_top; endmodule\n' }],
      level: 3,
      date: DATE,
    });
    await writeExport(tmp, out.files);
    const tcl = fs.readFileSync(path.join(tmp, 'create_project.tcl'), 'utf8');
    expect(tcl).not.toContain('\\\\');
    for (const m of tcl.matchAll(/\[file join \$here ([^\]]+)\]/g)) {
      const parts = m[1].split(' ').map((x) => x.replace(/[{}]/g, ''));
      if (parts[0] === 'vivado') continue;
      expect(fs.existsSync(path.join(tmp, ...parts)), m[1]).toBe(true);
    }
  });
});
